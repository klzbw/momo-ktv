fixed = 0
errors = 0

for dp, dns, fns in os.walk(out):
    rel = os.path.relpath(dp, out)
    # 匹配在路上CDxx目录
    m = re.search(r'在路上CD(\d+)', rel)
    if not m:
        continue
    cd_num = int(m.group(1))
    if cd_num not in CD_TRACKS:
        continue
    tracks = CD_TRACKS[cd_num]
    
    for fn in fns:
        if not fn.endswith('.flac'): continue
        name = fn[:-5]
        parts = name.split('-', 3)
        if len(parts) != 4: continue
        artist, title, lang, style = parts
        
        # 匹配音轨序号xx
        tm = re.match(r'^音轨序号(\d+)', title)
        if not tm:
            continue
        idx = int(tm.group(1)) - 1
        if idx >= len(tracks):
            continue
        
        new_title = tracks[idx]
        new_fn = f'{artist}-{new_title}-{lang}-{style}.flac'
        old_path = os.path.join(dp, fn)
        new_path = os.path.join(dp, new_fn)
        
        try:
            if os.path.exists(new_path):
                os.remove(old_path)
            else:
                os.rename(old_path, new_path)
            fixed += 1
        except Exception as e:
            errors += 1

print(f'修复在路上音轨序号: {fixed} 个')
print(f'错误: {errors} 个')
